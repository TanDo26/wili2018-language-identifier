@app.post("/api/v1/report", status_code=status.HTTP_201_CREATED, summary="Submit misclassification report")
def report_issue(payload: ReportRequest):
    labels_map = ML_COMPONENTS.get("labels_map", {})

    # Validate suggested language ISO code if present
    if payload.suggested_language and payload.suggested_language not in labels_map:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"Invalid suggested_language ISO code: '{payload.suggested_language}'."
        )

    conn = get_db_connection()
    cursor = conn.cursor()

    # Verify if prediction_id exists
    cursor.execute("SELECT prediction_id FROM predictions WHERE prediction_id = ?", (payload.prediction_id,))
    if not cursor.fetchone():
        conn.close()
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Prediction ID '{payload.prediction_id}' not found."
        )

    cursor.execute("""
        INSERT INTO reports (prediction_id, reason, suggested_language, comment)
        VALUES (?, ?, ?, ?)
    """, (payload.prediction_id, payload.reason.value, payload.suggested_language, payload.comment))
    
    report_id = cursor.lastrowid
    conn.commit()
    conn.close()

    return {"message": "Report created successfully", "report_id": report_id}


@app.get("/api/v1/reports", response_model=List[ReportItem], summary="List feedback reports (Admin)")
def list_reports(
    status_filter: Optional[str] = Query(None, alias="status"),
    model_version_filter: Optional[str] = Query(None, alias="model_version"),
    admin_auth: None = Header(None, alias="X-Admin-Token")
):
    verify_admin_auth(admin_auth)
    
    conn = get_db_connection()
    cursor = conn.cursor()

    query = """
        SELECT r.id as report_id, r.prediction_id, r.created_at, r.reason, 
               r.suggested_language, r.comment, r.status, r.verified_language,
               p.text, p.predicted_language, p.confidence, p.model_version
        FROM reports r
        JOIN predictions p ON r.prediction_id = p.prediction_id
        WHERE 1=1
    """
    params = []

    if status_filter:
        query += " AND r.status = ?"
        params.append(status_filter)
    if model_version_filter:
        query += " AND p.model_version = ?"
        params.append(model_version_filter)

    query += " ORDER BY r.id DESC"

    cursor.execute(query, params)
    rows = cursor.fetchall()
    conn.close()

    items = []
    for row in rows:
        items.append(ReportItem(
            report_id=row["report_id"],
            prediction_id=row["prediction_id"],
            created_at=str(row["created_at"]),
            reason=row["reason"],
            suggested_language=row["suggested_language"],
            comment=row["comment"],
            text=row["text"],
            predicted_language=row["predicted_language"],
            confidence=row["confidence"],
            model_version=row["model_version"],
            status=row["status"],
            verified_language=row["verified_language"]
        ))
    return items


@app.patch("/api/v1/reports/{report_id}", summary="Update report verification status (Admin)")
def update_report(
    report_id: int,
    payload: ReportUpdate,
    admin_auth: None = Header(None, alias="X-Admin-Token")
):
    verify_admin_auth(admin_auth)
    labels_map = ML_COMPONENTS.get("labels_map", {})

    if payload.status == "accepted":
        if not payload.verified_language:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="verified_language is required when status is accepted."
            )
        if payload.verified_language not in labels_map:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=f"Invalid verified_language ISO code: '{payload.verified_language}'."
            )

    conn = get_db_connection()
    cursor = conn.cursor()

    cursor.execute("SELECT id FROM reports WHERE id = ?", (report_id,))
    if not cursor.fetchone():
        conn.close()
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Report ID {report_id} not found."
        )

    cursor.execute("""
        UPDATE reports 
        SET status = ?, verified_language = ?
        WHERE id = ?
    """, (payload.status.value, payload.verified_language, report_id))

    conn.commit()
    conn.close()

    return {"message": "Report status updated successfully"}


@app.get("/api/v1/models", response_model=List[ModelVersion], summary="List model versions")
def list_models():
    models_dir = get_models_dir()
    active_version = ML_COMPONENTS.get("active_version")
    history = ML_COMPONENTS.get("version_history", [])
    
    versions_list = []
    if models_dir.exists():
        for path in models_dir.iterdir():
            if path.is_dir():
                v_name = path.name
                metrics_file = path / "metrics.json"
                meta_file = path / "meta.json"

                accuracy = 0.0
                macro_f1 = 0.0
                algorithm = "Unknown Algorithm"
                created_at = None

                if metrics_file.exists():
                    try:
                        with open(metrics_file, "r", encoding="utf-8") as f:
                            m_data = json.load(f)
                            accuracy = m_data.get("accuracy", 0.0)
                            macro_f1 = m_data.get("macro_f1", 0.0)
                    except Exception:
                        pass

                if meta_file.exists():
                    try:
                        with open(meta_file, "r", encoding="utf-8") as f:
                            meta_data = json.load(f)
                            algorithm = meta_data.get("algorithm", algorithm)
                            created_at = meta_data.get("created_at", None)
                    except Exception:
                        pass

                # Infer model status
                if v_name == active_version:
                    v_status = "active"
                elif v_name in history:
                    v_status = "archived"
                else:
                    v_status = "candidate"

                versions_list.append(ModelVersion(
                    version=v_name,
                    algorithm=algorithm,
                    status=v_status,
                    created_at=created_at,
                    accuracy=accuracy,
                    macro_f1=macro_f1
                ))

    return versions_list


@app.post("/api/v1/models/promote", summary="Promote model version (Admin)")
def promote_model(
    payload: PromoteRequest,
    admin_auth: None = Header(None, alias="X-Admin-Token")
):
    verify_admin_auth(admin_auth)
    target_version = payload.version
    models_dir = get_models_dir()

    if not (models_dir / target_version).exists():
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Model version '{target_version}' does not exist."
        )

    if target_version == ML_COMPONENTS.get("active_version"):
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail=f"Model version '{target_version}' is already active."
        )

    success = load_model_version(target_version)
    if not success:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to load target version '{target_version}'."
        )

    return {"message": f"Successfully promoted model version to {target_version}"}


@app.post("/api/v1/models/rollback", summary="Rollback to previous model version (Admin)")
def rollback_model(admin_auth: None = Header(None, alias="X-Admin-Token")):
    verify_admin_auth(admin_auth)
    history = ML_COMPONENTS.get("version_history", [])

    if not history:
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="No previous model version available in history to rollback."
        )

    previous_version = history.pop()
    
    # Direct load bypassing history appending
    models_dir = get_models_dir()
    version_path = models_dir / previous_version / "model.joblib"
    
    if not version_path.exists():
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Model artifact for previous version '{previous_version}' no longer exists."
        )

    ML_COMPONENTS["model"] = joblib.load(version_path)
    ML_COMPONENTS["active_version"] = previous_version

    conn = get_db_connection()
    cursor = conn.cursor()
    cursor.execute(
        "INSERT OR REPLACE INTO system_config (key, value) VALUES ('active_version', ?)",
        (previous_version,)
    )
    conn.commit()
    conn.close()

    return {"message": f"Successfully rolled back model version to {previous_version}"}
