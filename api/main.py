# Inference Core Business Logic
# -----------------------------------------------------------------------------
def execute_inference(text: str) -> PredictResponse:
    model = ML_COMPONENTS.get("model")
    active_version = ML_COMPONENTS.get("active_version")
    labels_map = ML_COMPONENTS.get("labels_map", {})

    if not model or not active_version:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Model is not loaded or unavailable."
        )

    # Optional text normalization if module exists
    try:
        from data.common import normalize_text
        processed_text = normalize_text(text)
    except ImportError:
        processed_text = text.strip()

    # Probability inference calculation
    probabilities = model.predict_proba([processed_text])[0]
    classes = model.classes_

    top_indices = probabilities.argsort()[::-1][:3]
    top_candidates = []

    for idx in top_indices:
        code = str(classes[idx])
        conf = float(round(probabilities[idx], 4))
        name = labels_map.get(code, code)
        top_candidates.append(Candidate(code=code, name=name, confidence=conf))

    top_1 = top_candidates[0]
    confidence = top_1.confidence
    
    unsure_threshold = get_unsure_threshold()
    is_unsure = confidence < unsure_threshold

    explanations = []
    if is_unsure:
        explanations.append(f"Low confidence score: prediction confidence ({confidence}) is below threshold ({unsure_threshold}).")
    if len(top_candidates) > 1 and (top_1.confidence - top_candidates[1].confidence) < 0.15:
        explanations.append(f"Top predictions '{top_1.name}' and '{top_candidates[1].name}' have close confidence scores.")

    prediction_id = str(uuid.uuid4())

    # Save prediction record to persistent SQLite database
    conn = get_db_connection()
    cursor = conn.cursor()
    cursor.execute("""
        INSERT INTO predictions (prediction_id, text, predicted_language, confidence, model_version)
        VALUES (?, ?, ?, ?, ?)
    """, (prediction_id, text, top_1.code, confidence, active_version))
    conn.commit()
    conn.close()

    return PredictResponse(
        prediction_id=prediction_id,
        model_version=active_version,
        language_code=top_1.code,
        language_name=top_1.name,
        confidence=confidence,
        is_unsure=is_unsure,
        explanation=explanations,
        top_candidates=top_candidates
    )


