# -----------------------------------------------------------------------------
# Config & Paths Environment Management
# -----------------------------------------------------------------------------
BASE_DIR = Path(__file__).resolve().parent.parent

def get_models_dir() -> Path:
    return Path(os.getenv("MODELS_DIR", BASE_DIR / "models"))

def get_db_path() -> Path:
    return Path(os.getenv("DB_PATH", BASE_DIR / "database" / "reports.db"))

def get_admin_token() -> str:
    return os.getenv("ADMIN_TOKEN", "default-secret-token")

def get_unsure_threshold() -> float:
    return float(os.getenv("UNSURE_THRESHOLD", "0.8"))


# -----------------------------------------------------------------------------
# Global State Management
# -----------------------------------------------------------------------------
ML_COMPONENTS: Dict[str, Any] = {
    "model": None,
    "active_version": None,
    "labels_map": {},      # code -> name
    "version_history": []   # stack for rollback operation
}


# -----------------------------------------------------------------------------
# Database Initialization & Helpers
# -----------------------------------------------------------------------------
def get_db_connection() -> sqlite3.Connection:
    db_file = get_db_path()
    db_file.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(db_file)
    conn.row_factory = sqlite3.Row
    return conn


def init_db():
    conn = get_db_connection()
    cursor = conn.cursor()
    
    # Stores predictions generated by the models
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS predictions (
            prediction_id TEXT PRIMARY KEY,
            text TEXT NOT NULL,
            predicted_language TEXT NOT NULL,
            confidence REAL NOT NULL,
            model_version TEXT NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    """)

    # Stores user feedback reports
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS reports (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            prediction_id TEXT NOT NULL,
            reason TEXT NOT NULL,
            suggested_language TEXT,
            comment TEXT,
            status TEXT DEFAULT 'new',
            verified_language TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (prediction_id) REFERENCES predictions(prediction_id)
        )
    """)

    # Stores system runtime configuration and active version state
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS system_config (
            key TEXT PRIMARY KEY,
            value TEXT NOT NULL
        )
    """)

    conn.commit()
    conn.close()


def load_labels() -> Dict[str, str]:
    labels_path = BASE_DIR / "data" / "processed" / "labels.csv"
    labels_map = {}
    if labels_path.exists():
        with open(labels_path, mode="r", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            for row in reader:
                labels_map[row["code"]] = row["name"]
    return labels_map


def load_model_version(version: str) -> bool:
    models_dir = get_models_dir()
    version_path = models_dir / version / "model.joblib"

    if not version_path.exists():
        return False

    model = joblib.load(version_path)
    
    # Push current version to rollback history stack before updating state
    current_ver = ML_COMPONENTS.get("active_version")
    if current_ver and current_ver != version:
        ML_COMPONENTS["version_history"].append(current_ver)

    ML_COMPONENTS["model"] = model
    ML_COMPONENTS["active_version"] = version

    # Sync state to SQLite DB
    conn = get_db_connection()
    cursor = conn.cursor()
    cursor.execute(
        "INSERT OR REPLACE INTO system_config (key, value) VALUES ('active_version', ?)",
        (version,)
    )
    conn.commit()
    conn.close()
    return True


def discover_active_version() -> Optional[str]:
    # Check DB persistent state first
    conn = get_db_connection()
    cursor = conn.cursor()
    cursor.execute("SELECT value FROM system_config WHERE key = 'active_version'")
    row = cursor.fetchone()
    conn.close()

    if row:
        return row["value"]

    # Fallback to scan disk for available directories
    models_dir = get_models_dir()
    if models_dir.exists():
        versions = [d.name for d in models_dir.iterdir() if d.is_dir()]
        if versions:
            versions.sort()
            return versions[0]
            
    return None


# -----------------------------------------------------------------------------
# Lifespan Context Manager
# -----------------------------------------------------------------------------
@asynccontextmanager
async def lifespan(app: FastAPI):
    init_db()
    ML_COMPONENTS["labels_map"] = load_labels()

    active_ver = discover_active_version()
    if active_ver:
        loaded = load_model_version(active_ver)
        if loaded:
            print(f"--> Successfully loaded active model version: {active_ver}")
        else:
            print(f"--> WARN: Failed to load artifact for version: {active_ver}")
    else:
        print("--> WARN: No model versions found in directory.")

    yield

    ML_COMPONENTS.clear()


# -----------------------------------------------------------------------------
# FastAPI Application & Exception Handlers
# -----------------------------------------------------------------------------
app = FastAPI(
    title="HTTM API - Language Identification System",
    version="0.1.0",
    description="Backend API serving WiLI-2018 language identification models",
    lifespan=lifespan
)


@app.exception_handler(RequestValidationError)
async def custom_validation_error_handler(request: Request, exc: RequestValidationError):
    """Custom validation handler mapping oversized payloads to 413 and invalid inputs to 400."""
    too_long = any(e["type"] in ("string_too_long", "too_long") for e in exc.errors())
    status_code = status.HTTP_413_REQUEST_ENTITY_TOO_LARGE if too_long else status.HTTP_400_BAD_REQUEST
    error_msg = "; ".join(e["msg"] for e in exc.errors())
    return JSONResponse(
        status_code=status_code,
        content={"detail": error_msg}
    )


def verify_admin_auth(x_admin_token: Optional[str] = Header(None)):
    if not x_admin_token or x_admin_token != get_admin_token():
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid or missing admin token."
        )


